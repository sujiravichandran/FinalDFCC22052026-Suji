package com.teclever.dfcc.model;

public class LRUTest {

	
	String fileName;
	String result;
	String faultPinSuggestion;
	String interfaceSignal;
	String channel;



	public String getFileName() {
		return fileName;
	}



	public void setFileName(String fileName) {
		this.fileName = fileName;
	}



	public String getResult() {
		return result;
	}



	public void setResult(String result) {
		this.result = result;
	}



	public String getFaultPinSuggestion() {
		return faultPinSuggestion;
	}



	public void setFaultPinSuggestion(String faultPinSuggestion) {
		this.faultPinSuggestion = faultPinSuggestion;
	}



	public String getInterfaceSignal() {
		return interfaceSignal;
	}



	public void setInterfaceSignal(String interfaceSignal) {
		this.interfaceSignal = interfaceSignal;
	}



	public String getChannel() {
		return channel;
	}



	public void setChannel(String channel) {
		this.channel = channel;
	}
	
	
	
}
