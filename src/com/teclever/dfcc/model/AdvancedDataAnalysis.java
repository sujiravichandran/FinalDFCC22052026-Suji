package com.teclever.dfcc.model;

public class AdvancedDataAnalysis {

	private String slNo;
	private String uttType;
	private String sessionTypeName;
	private int count;
	
	
	public String getUttType() {
		return uttType;
	}
	public void setUttType(String uttType) {
		this.uttType = uttType;
	}
	public int getCount() {
		return count;
	}
	public void setCount(int count) {
		this.count = count;
	}
	public String getSessionTypeName() {
		return sessionTypeName;
	}
	public void setSessionTypeName(String sessionTypeName) {
		this.sessionTypeName = sessionTypeName;
	}

	public String getSlNo() {
		return slNo;
	}
	public void setSlNo(String slNo) {
		this.slNo = slNo;
	}
	
	
}
