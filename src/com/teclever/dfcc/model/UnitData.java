package com.teclever.dfcc.model;

public class UnitData {

	private int id;
	private String slNo;
	private String sessionType;
	private String sessonName;
	private String startTime;
	private String endTime;
	private String sessionStatus;
	private String sessionResult;
	
	
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getSlNo() {
		return slNo;
	}
	public void setSlNo(String slNo) {
		this.slNo = slNo;
	}
	public String getSessionType() {
		return sessionType;
	}
	public void setSessionType(String sessionType) {
		this.sessionType = sessionType;
	}
	public String getSessonName() {
		return sessonName;
	}
	public void setSessonName(String sessonName) {
		this.sessonName = sessonName;
	}
	public String getStartTime() {
		return startTime;
	}
	public void setStartTime(String startTime) {
		this.startTime = startTime;
	}
	public String getEndTime() {
		return endTime;
	}
	public void setEndTime(String endTime) {
		this.endTime = endTime;
	}
	public String getSessionStatus() {
		return sessionStatus;
	}
	public void setSessionStatus(String sessionStatus) {
		this.sessionStatus = sessionStatus;
	}
	public String getSessionResult() {
		return sessionResult;
	}
	public void setSessionResult(String sessionResult) {
		this.sessionResult = sessionResult;
	}
	
	
}
