package com.teclever.dfcc.datastore.dto;

public class FaultySRUDto {
	
	private String rdfFileName;
    private String tpgph;
    private String step;
    private String signalName;
    private String faultySRU;
	public String getRdfFileName() {
		return rdfFileName;
	}
	public void setRdfFileName(String rdfFileName) {
		this.rdfFileName = rdfFileName;
	}
	public String getTpgph() {
		return tpgph;
	}
	public void setTpgph(String tpgph) {
		this.tpgph = tpgph;
	}
	public String getStep() {
		return step;
	}
	public void setStep(String step) {
		this.step = step;
	}
	public String getSignalName() {
		return signalName;
	}
	public void setSignalName(String signalName) {
		this.signalName = signalName;
	}
	public String getFaultySRU() {
		return faultySRU;
	}
	public void setFaultySRU(String faultySRU) {
		this.faultySRU = faultySRU;
	}
    
    

}
